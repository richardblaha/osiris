// Turns the official Kubernetes icons (github.com/kubernetes/community, icons/svg; Apache-2.0 or CC-BY-4.0) into
// outline icons for the twin: only their geometry is kept (no metadata, scripts or styles), each shape tagged as the
// heptagon (`bg`), a filled part of the symbol (`glyph`) or a stroked one (`line`); the white rim is dropped. The view
// draws them as strokes in the theme's colours. Run with the folder of the downloaded SVGs:
//   node server/digital-twin/web/scripts/k8s-icons.mjs <folder>   (writes src/k8s-icons.ts)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS = ["ns", "pod", "sts", "deploy", "ds", "job", "cronjob", "rs", "pvc", "node", "control-plane"];
const SHAPES = new Set(["path", "rect", "circle", "ellipse", "polygon", "polyline"]);
const GEOMETRY = ["d", "x", "y", "width", "height", "rx", "ry", "cx", "cy", "r", "points", "transform"];
const SKIP = new Set(["metadata", "defs", "sodipodi:namedview", "title", "desc", "text", "tspan", "flowRoot", "script", "style"]);

const attrsOf = (raw) => Object.fromEntries([...raw.matchAll(/([\w:-]+)\s*=\s*"([^"]*)"/g)].map((m) => [m[1], m[2]]));
const styleOf = (a) => ({ ...Object.fromEntries((a.style ?? "").split(";").map((p) => p.split(":").map((s) => s.trim())).filter((p) => p.length === 2)), ...(a.fill ? { fill: a.fill } : {}), ...(a.stroke ? { stroke: a.stroke } : {}) });
const safe = (v) => /^[-0-9a-zA-Z.,\s()]*$/.test(v);
const white = (c) => /^#?(fff|ffffff|white)$/i.test(c ?? "");

function convert(svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  if (!safe(viewBox)) throw new Error("bad viewBox");
  let out = "";
  let skipping = 0;
  let sawBg = false;
  let rimDropped = false;
  for (const m of svg.matchAll(/<(\/?)([\w:]+)([^>]*?)(\/?)>/g)) {
    const [, close, tag, raw, selfClose] = m;
    if (SKIP.has(tag)) {
      if (!selfClose) skipping += close ? -1 : 1;
      continue;
    }
    if (skipping > 0 || tag === "svg" || tag === "?xml") continue;
    if (tag === "g") {
      if (close) out += "</g>";
      else {
        const t = attrsOf(raw).transform;
        out += t && safe(t) ? `<g transform="${t}">` : "<g>";
        if (selfClose) out += "</g>";
      }
      continue;
    }
    if (!SHAPES.has(tag) || close) continue;
    const a = attrsOf(raw);
    const s = styleOf(a);
    let cls;
    if (/^#326ce5$/i.test(s.fill ?? "")) (cls = "bg"), (sawBg = true);
    else if (white(s.fill) && sawBg && !rimDropped) {
      rimDropped = true;
      continue;
    } else if (white(s.fill)) cls = "glyph";
    else if (white(s.stroke)) cls = "line";
    else continue;
    const dash = s["stroke-dasharray"] && s["stroke-dasharray"] !== "none" && safe(s["stroke-dasharray"]) ? ` stroke-dasharray="${s["stroke-dasharray"]}"` : "";
    const geometry = GEOMETRY.filter((k) => a[k] !== undefined && safe(a[k])).map((k) => `${k}="${a[k]}"`).join(" ") + dash;
    out += `<${tag} class="${cls}" ${geometry}/>`;
  }
  return { viewBox, body: out };
}

const dir = process.argv[2];
const icons = Object.fromEntries(ICONS.map((name) => [name, convert(readFileSync(join(dir, `${name}.svg`), "utf8"))]));
writeFileSync(
  join(import.meta.dirname, "../src/k8s-icons.ts"),
  `// Generated by scripts/k8s-icons.mjs from the Kubernetes icons set (github.com/kubernetes/community, icons/svg),
// licensed under Apache-2.0 or CC-BY-4.0; the Kubernetes logo is a registered trademark of The Linux Foundation.
// Only geometry is kept; classes: bg (the heptagon), glyph (a filled part of the symbol), line (a stroked one).
export const K8S_ICONS: Record<string, { viewBox: string; body: string }> = ${JSON.stringify(icons, null, 2)};
`,
);
