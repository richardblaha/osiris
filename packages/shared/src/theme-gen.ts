/**
 * The clients' theme made from richardblaha/osiris-theme's `assets/tokens.json` (a release's copy in
 * `packages/shared/theme/`): the CSS variables between the markers of every PWA's `theme.css` and
 * `src/theme-tokens.ts`. `pnpm --filter @osiris/shared theme [<tag>]` writes them (with a tag it fetches that
 * release's tokens first); `test/theme.test.ts` fails when a file differs from what this makes.
 */

type Scheme = "dark" | "light";
type Pair = Record<Scheme, string>;

export interface Tokens {
  font: { ui: string; mono: string };
  radius: Record<"xs" | "sm" | "md" | "lg" | "xl", number>;
  shadow: { window: string; popup: string };
  accent: Record<"primary" | "primarySoft" | "secondary" | "secondarySoft", Pair>;
  state: Record<"info" | "success" | "warning" | "error", Pair>;
  themes: Record<
    Scheme,
    {
      bg: Record<string, string>;
      border: Record<string, string>;
      text: Record<string, string>;
      syntax: Record<string, string>;
      scrollbar: string;
    }
  >;
}

/** The PWAs whose `theme.css` carries the tokens (osiris-auth's pages import the PWA's, the desktop page copies it). */
export const THEME_CSS_FILES = ["apps/osiris-pwa/src/theme.css", "server/digital-twin/web/src/theme.css"];

export const BEGIN = "/* osiris-theme tokens: generated by `pnpm --filter @osiris/shared theme`, do not edit by hand */";
export const END = "/* end of osiris-theme tokens */";

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const noComments = (o: Record<string, unknown>) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith("$")));
/** `Fira Code, ui-monospace, Segoe UI` → `"Fira Code", ui-monospace, "Segoe UI"`. */
const fontList = (s: string) =>
  s
    .split(",")
    .map((f) => f.trim())
    .map((f) => (/\s/.test(f) && !/^["']/.test(f) ? `"${f}"` : f))
    .join(", ");

function colors(t: Tokens, s: Scheme): string[] {
  const th = t.themes[s];
  const group = (prefix: string, o: Record<string, string>) =>
    Object.entries(noComments(o)).map(([k, v]) => `--${prefix}-${kebab(k)}: ${v};`);
  return [
    `/* themes.${s} */`,
    ...group("bg", th.bg),
    ...group("border", th.border),
    ...group("text", th.text),
    `--scrollbar: ${th.scrollbar};`,
    ...group("syntax", th.syntax),
    "",
    ...Object.entries(t.accent).map(([k, v]) => `--accent-${kebab(k)}: ${v[s]};`),
    ...Object.entries(t.state).map(([k, v]) => `--state-${kebab(k)}: ${v[s]};`),
  ];
}

/** The block of CSS variables, markers included: light in `:root`, dark under `prefers-color-scheme: dark`. */
export function tokensCss(t: Tokens, release: string): string {
  const indent = (lines: string[], n: number) => lines.map((l) => (l ? " ".repeat(n) + l : l));
  return [
    BEGIN,
    `/* richardblaha/osiris-theme ${release}, assets/tokens.json. Light is the baseline, dark applies under */`,
    "/* prefers-color-scheme: dark (the theme's Forgejo `auto` pattern). */",
    ":root {",
    "  color-scheme: light dark;",
    "",
    `  --font-ui: ${fontList(t.font.ui)};`,
    `  --radius: ${t.radius.sm}px; /* radius.sm/md: one slight rounding, no pills */`,
    `  --shadow-popup: ${t.shadow.popup};`,
    "",
    ...indent(colors(t, "light"), 2),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    ...indent(colors(t, "dark"), 4),
    "  }",
    "}",
    END,
  ].join("\n");
}

/** `src/theme-tokens.ts`: the release's tokens the clients draw with, without its comments, icons and wallpapers. */
export function tokensTs(t: Tokens, release: string): string {
  const strip = (v: unknown): unknown =>
    v && typeof v === "object" && !Array.isArray(v)
      ? Object.fromEntries(Object.entries(noComments(v as Record<string, unknown>)).map(([k, x]) => [k, strip(x)]))
      : v;
  const theme = {
    release,
    font: { ui: t.font.ui, mono: t.font.mono },
    radius: t.radius,
    shadow: t.shadow,
    accent: t.accent,
    state: t.state,
    themes: Object.fromEntries((["dark", "light"] as const).map((s) => {
      const { bg, border, text, syntax, scrollbar } = t.themes[s];
      return [s, { bg, border, text, syntax, scrollbar }];
    })),
  };
  return [
    `// Generated by \`pnpm --filter @osiris/shared theme\` from richardblaha/osiris-theme ${release} (assets/tokens.json): do not edit.`,
    `export const OSIRIS_THEME = ${JSON.stringify(strip(theme), null, 2)} as const;`,
    "",
  ].join("\n");
}

/** `file` with its block between the markers replaced by `block`; a file without the markers is an error. */
export function withTokens(file: string, block: string): string {
  const from = file.indexOf(BEGIN);
  const to = file.indexOf(END);
  if (from < 0 || to < from) throw new Error("theme.css has no osiris-theme tokens block");
  return file.slice(0, from) + block + file.slice(to + END.length);
}

/** The variables the block sets, so a test can check an app doesn't set them again elsewhere. */
export const tokenVariables = (block: string) => [...new Set([...block.matchAll(/(--[a-z0-9-]+):/g)].map((m) => m[1]!))];
