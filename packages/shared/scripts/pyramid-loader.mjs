// Generates the pyramid loader (`public/splash.svg` of the PWA and the digital twin): the k6labs pyramid turning
// about its vertical axis as SMIL keyframes, so it animates in an <img> without any script.
//   node packages/shared/scripts/pyramid-loader.mjs
import { writeFileSync } from "node:fs";
import { join } from "node:path";

// The k6labs pyramid turning about its vertical axis, as SMIL keyframes. The logo's base is seen in perspective
// (left and right corners at y 130, the front one 40 below, the back one 20 above), so a base corner at angle a, depth
// z = sin a toward the viewer, projects with the scale 1 / (1 - z/3). At turn 0 it is exactly the logo.
const STEPS = 48, PERIOD = 3.2;
const apex = [100, 30];
const vertex = (a) => {
  const z = Math.sin(a);
  const k = 1 / (1 - z / 3);
  return [100 + 80 * Math.cos(a) * k, 130 + (80 / 3) * z * k];
};
const f = (n) => Math.round(n * 100) / 100;
const pts = (list) => list.map(([x, y]) => `${f(x)},${f(y)}`).join(" ");
// Base vertices at turn φ: 180° (left), 90° (front), 0° (right), 270° (back) at φ = 0.
const frames = Array.from({ length: STEPS + 1 }, (_, i) => -(i / STEPS) * 2 * Math.PI);
const base = (phi) => [Math.PI, Math.PI / 2, 0, (3 * Math.PI) / 2].map((a) => a + phi);
const face = (k, phi) => { const b = base(phi); return [apex, vertex(b[k]), vertex(b[(k + 1) % 4])]; };
// A face shows while it turns towards the viewer: its middle direction points to the front (sin > 0).
// A face shows while it turns towards the viewer: its projected triangle winds the way the logo's front faces do.
const area = ([a, b, c]) => (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]);
const visible = (k, phi) => area(face(k, phi)) * area(face(0, 0)) > 1e-6;
const keyTimes = frames.map((_, i) => f(i / STEPS)).join(";");
const anim = (attr, values, discrete = false) =>
  `<animate attributeName="${attr}" dur="${PERIOD}s" repeatCount="indefinite" keyTimes="${keyTimes}" values="${values.join(";")}"${discrete ? ' calcMode="discrete"' : ""}/>`;
const fills = ["url(#p-cyan)", "url(#p-rose)", "url(#p-cyan)", "url(#p-rose)"];
let faces = "";
for (let k = 0; k < 4; k++) {
  faces += `  <polygon fill="${fills[k]}" points="${pts(face(k, 0))}" opacity="${visible(k, 0) ? 1 : 0}">\n    ${anim("points", frames.map((p) => pts(face(k, p))))}\n    ${anim("opacity", frames.map((p) => (visible(k, p) ? 1 : 0)), true)}\n  </polygon>\n`;
}
const shade = `  <polygon fill="#000" opacity="0.35" points="${pts(base(0).map(vertex))}">\n    ${anim("points", frames.map((p) => pts(base(p).map(vertex))))}\n  </polygon>\n`;
// The edge nearest the viewer, in white, fading as it turns away.
let edges = "";
for (let k = 0; k < 4; k++) {
  const op = (p) => f(Math.max(0, Math.sin(base(p)[k])) ** 4 * 0.6);
  const v = (p) => vertex(base(p)[k]);
  edges += `  <line x1="100" y1="30" x2="${f(v(0)[0])}" y2="${f(v(0)[1])}" stroke="#fff" stroke-width="3" opacity="${op(0)}">\n    ${anim("x2", frames.map((p) => f(v(p)[0])))}\n    ${anim("y2", frames.map((p) => f(v(p)[1])))}\n    ${anim("opacity", frames.map(op))}\n  </line>\n`;
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="15 25 170 150">
  <!-- The k6labs pyramid turning about its vertical axis (generated by packages/shared/scripts/pyramid-loader.mjs; at turn 0 it is the logo). -->
  <defs>
    <linearGradient id="p-cyan" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#00f2fe"/><stop offset="1" stop-color="#00b4d8"/></linearGradient>
    <linearGradient id="p-rose" x1="1" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#ff2a85"/><stop offset="1" stop-color="#c81d67"/></linearGradient>
  </defs>
${faces}${shade}${edges}</svg>
`;

const root = join(import.meta.dirname, "../../..");
for (const target of ["apps/osiris-pwa/public/splash.svg", "server/digital-twin/web/public/splash.svg"]) writeFileSync(join(root, target), svg);
