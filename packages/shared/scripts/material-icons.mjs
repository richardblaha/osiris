// Generates src/material-icons.ts: the Material Symbols (Outlined, weight 400; Google, Apache-2.0) the clients use,
// as SVG paths in a 960×960 box (viewBox "0 -960 960 960"). Only the icons named here go into the bundles; add a
// name and run `pnpm --filter @osiris/shared icons`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const ICONS = [
  "add", "arrow_back", "arrow_downward", "arrow_forward", "arrow_upward", "attach_file", "bar_chart", "chat",
  "check", "check_circle", "chevron_left", "chevron_right", "close", "dashboard", "database", "delete", "description",
  "draft", "error", "extension", "folder", "forum", "group", "image", "inventory_2", "keyboard_arrow_down", "key", "language",
  "left_panel_close", "left_panel_open", "menu_book", "mic", "open_in_new", "psychology", "remove", "schedule",
  "school", "send", "settings", "star", "stop", "support_agent", "verified_user", "volume_off", "volume_up", "warning",
];

const root = dirname(createRequire(import.meta.url).resolve("@material-symbols/svg-400/package.json"));
const paths = ICONS.map((name) => {
  const svg = readFileSync(join(root, "outlined", `${name}.svg`), "utf8");
  const d = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!d) throw new Error(`No path in ${name}.svg`);
  return `  ${name}: "${d}",`;
});
const out = `// Generated by scripts/material-icons.mjs from @material-symbols/svg-400 (Material Symbols Outlined, Apache-2.0).
// Do not edit: add the name there and run \`pnpm --filter @osiris/shared icons\`.

/** Material Symbols' paths, in the box \`viewBox="0 -960 960 960"\`. */
export const MATERIAL_ICONS = {
${paths.join("\n")}
} as const;

export type MaterialIcon = keyof typeof MATERIAL_ICONS;
export const MATERIAL_VIEWBOX = "0 -960 960 960";
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../src/material-icons.ts"), out);
console.log(`${ICONS.length} icons`);
